#include <stdio.h>
#include <string.h>
 // 如需使用HAL_Delay，需确保包含对应的头文件

/**
 * @brief  串口发送字符串（阻塞式）
 * @param  huart: 串口句柄
 * @param  str: 要发送的字符串
 * @retval 无
 */
void USART1_SendString(const char *str)
{
  if(str == NULL) return;
  
  uint32_t len = strlen(str);
  for(uint32_t i = 0; i < len; i++)
  {
    // 等待发送寄存器为空
    while(!LL_USART_IsActiveFlag_TXE(USART1));
    // 发送单个字节
    LL_USART_TransmitData8(USART1, str[i]);
  }
  // 等待发送完成
  while(!LL_USART_IsActiveFlag_TC(USART1));
}

/**
 * @brief  循环发送1-100的数值到串口
 * @param  interval_ms: 每次发送的间隔时间(ms)
 * @retval 无
 */
void USART1_Send_1_to_100(uint32_t interval_ms)
{
  char send_buf[32];  // 存储格式化后的字符串
  
  while(1)  // 无限循环发送
  {
    for(int i = 1; i <= 100; i++)
    {
      // 将数字格式化为字符串，添加换行回车便于串口助手查看
      snprintf(send_buf, sizeof(send_buf), "Number: %d\r\n", i);
      
      // 发送格式化后的字符串
      USART1_SendString(send_buf);
      
      // 延时指定时间，避免发送过快
      for(volatile uint32_t delay = 0; delay < interval_ms * 1000; delay++);
      // 如果你的工程有HAL库，可以替换为：HAL_Delay(interval_ms);
    }
    
    // 每发送完1-100后，发送分隔符
    USART1_SendString("-------------------\r\n");
  }
}

